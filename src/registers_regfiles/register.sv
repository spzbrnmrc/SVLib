`timescale 1ns / 1ps

module register #(
    parameter integer WIDTH = 1
) (
    input logic clk,

    input  logic [WIDTH-1:0] din,
    output logic [WIDTH-1:0] dout
);

  always_ff @(posedge clk) begin
    dout <= din;
  end

endmodule
